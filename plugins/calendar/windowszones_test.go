package main

import (
	"bytes"
	"encoding/xml"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"slices"
	"strings"
	"testing"
	"time"
)

// cldrWindowsZones is CLDR's table of Windows time zones, at the release
// windowszones.go was made from.
const cldrWindowsZones = "https://raw.githubusercontent.com/unicode-org/cldr/release-49/common/supplemental/windowsZones.xml"

var update = flag.Bool("update", false, "rewrite windowszones.go from "+cldrWindowsZones)

// TestWindowsZones checks that every zone windowsZones maps to loads;
// with -update it first rewrites windowszones.go from CLDR.
func TestWindowsZones(t *testing.T) {
	if *update {
		writeWindowsZones(t)
	}
	if len(windowsZones) < 100 {
		t.Fatalf("%d Windows zones, want CLDR's whole table", len(windowsZones))
	}
	for windows, iana := range windowsZones {
		if _, err := time.LoadLocation(iana); err != nil {
			t.Errorf("%q maps to %q: %v", windows, iana, err)
		}
	}
}

func writeWindowsZones(t *testing.T) {
	resp, err := http.Get(cldrWindowsZones)
	if err != nil {
		t.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("%s: %s", cldrWindowsZones, resp.Status)
	}
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		t.Fatal(err)
	}
	var doc struct {
		Zones []struct {
			Other     string `xml:"other,attr"`
			Territory string `xml:"territory,attr"`
			Type      string `xml:"type,attr"`
		} `xml:"windowsZones>mapTimezones>mapZone"`
	}
	if err := xml.Unmarshal(data, &doc); err != nil {
		t.Fatal(err)
	}
	var lines []string
	for _, z := range doc.Zones {
		// The zone for territory 001 is the one for the Windows zone as
		// a whole; the first name in type is its main one.
		if z.Territory == "001" {
			iana, _, _ := strings.Cut(z.Type, " ")
			lines = append(lines, fmt.Sprintf("\t%q: %q,\n", z.Other, iana))
		}
	}
	slices.Sort(lines)
	var b bytes.Buffer
	fmt.Fprintf(&b, `// SPDX-License-Identifier: GPL-3.0-or-later

// Code generated by "go test -run TestWindowsZones -update"; DO NOT EDIT.

package main

// windowsZones maps the names of Windows time zones, which feeds from
// Outlook and Exchange use, to IANA ones, from CLDR's windowsZones.xml
// (%s).
var windowsZones = map[string]string{
%s}
`, cldrWindowsZones, strings.Join(lines, ""))
	src, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile("windowszones.go", src, 0o644); err != nil {
		t.Fatal(err)
	}
}
