var update = flag.Bool("update", false, "rewrite zones.go from the Go toolchain's lib/time/zoneinfo.zip")

// TestZoneList checks that every zone in zoneList loads; with -update
// it first rewrites zones.go from the toolchain's time zone database.
func TestZoneList(t *testing.T) {
	if *update {
		writeZones(t)
	}
	if len(names) < 500 {
		t.Fatalf("%d zones, want the whole database", len(names))
	}
	for _, name := range names {
		if _, err := time.LoadLocation(name); err != nil {
			t.Errorf("zone %q: %v", name, err)
		}
	}
}

func writeZones(t *testing.T) {
	r, err := zip.OpenReader(filepath.Join(build.Default.GOROOT, "lib", "time", "zoneinfo.zip"))
	if err != nil {
		t.Fatal(err)
	}
	defer r.Close()
	var names []string
	seen := map[string]string{}
	for _, f := range r.File {
		if strings.HasSuffix(f.Name, "/") {
			continue
		}
		if other, ok := seen[strings.ToLower(f.Name)]; ok {
			t.Fatalf("zones %q and %q differ only in case", other, f.Name)
		}
		seen[strings.ToLower(f.Name)] = f.Name
		names = append(names, f.Name)
	}
	slices.Sort(names)
	var b bytes.Buffer
	fmt.Fprintf(&b, `// SPDX-License-Identifier: GPL-3.0-or-later

// Code generated by "go test -run TestZoneList -update"; DO NOT EDIT.

package zones

// zoneList is every time zone in the IANA database, one per line, as Go
// %s ships it in lib/time/zoneinfo.zip.
const zoneList = `+"`"+`%s`+"`\n", strings.TrimPrefix(runtime.Version(), "go"), strings.Join(names, "\n"))
	if err := os.WriteFile("zones.go", b.Bytes(), 0o644); err != nil {
		t.Fatal(err)
	}
	t.Skip("zones.go rewritten; run the tests again to check it")
}

func TestLoad(t *testing.T) {
	for _, tc := range []struct{ name, want string }{
		{"", "Local"},
		{"local", "Local"},
		{"Asia/Tokyo", "Asia/Tokyo"},
		{"asia/tokyo", "Asia/Tokyo"},
		{"AMERICA/PORT-AU-PRINCE", "America/Port-au-Prince"},
		{"utc", "UTC"},
		{" Europe/Berlin ", "Europe/Berlin"},
	} {
		if _, got, err := Load(tc.name); err != nil || got != tc.want {
			t.Errorf("Load(%q) = %q, %v; want %q", tc.name, got, err, tc.want)
		}
	}
	for _, name := range []string{"Mars/Olympus", "posix/Europe/Berlin", "right/UTC"} {
		if _, _, err := Load(name); err == nil {
			t.Errorf("Load(%q) succeeded", name)
		}
	}
}
